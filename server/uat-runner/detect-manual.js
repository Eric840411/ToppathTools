/**
 * server/uat-runner/detect-manual.js
 *
 * 「這筆 TC 機器判不了、要人工看」的判定。**runner 與 server 共用同一份**——
 * 各寫一份的話，畫面上算出來的「需人工」筆數會跟實際跑出來的對不起來，
 * 而且那種不一致沒有任何錯誤訊息，只會讓人以為統計壞了。
 *
 * ⚠️ 加 pattern 時兩個踩過的坑：
 *  ① TC 原文的 > 後面就換行，JS regex 的 . 預設不跨行，要用 [\s\S]
 *  ② 理由文字裡含 / 的話，用字串切割去 parse 這支檔案的工具會抓錯結尾——
 *     那是工具的限制不是 pattern 有問題，真正的驗證永遠是實際跑一次
 */
/**
 * detectManual(full) → 回傳 manualReason string 或 null
 */
