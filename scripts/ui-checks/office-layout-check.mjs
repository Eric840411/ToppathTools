/** 文書工具版面回歸。跑法：node scripts/ui-checks/office-layout-check.mjs <base url> <截圖目錄> */
// 文書工具版面：開了工具後工具格收起、工作區吃滿剩餘高度、開啟工具選單、放大；切版面 iframe 不能重建
import Database from 'better-sqlite3'
import { chromium } from 'playwright'
import { mintDevSession } from './lib/dev-session.mjs'

const [H, out] = process.argv.slice(2)
const db = new Database('server/data.db')
const { sid } = mintDevSession(db, 'eric.wu@toppath.tw', 1800000)
const u = new URL(H)
let fail = 0
const check = (n, ok, x = '') => { console.log(`  ${ok ? 'PASS' : 'FAIL'} ${n}${x ? '  ' + x : ''}`); if (!ok) fail++ }
const b = await chromium.launch()
const ctx = await b.newContext({ viewport: { width: 1440, height: 900 } })
await ctx.addCookies([{ name: 'toppath_auth', value: sid, domain: u.hostname, path: '/' }])
const p = await ctx.newPage()
await p.goto(H + '/', { waitUntil: 'networkidle' })
await p.locator('.sidebar-nav-item').filter({ hasText: /文書工具|文房四寶/ }).first().click()
await p.waitForSelector('.office-app')
check('還沒開工具：工具格在', await p.locator('.office-app').count() === 13)
await p.click('.office-app:has-text("Excel")')
await p.waitForTimeout(6000)
check('開了工具：工具格收起', await p.locator('.office-app').count() === 0)
const fr = await (await p.$('iframe.office-frame--active')).contentFrame()
await fr.evaluate(() => { window.__keep = 'kept' })
const geo = await p.evaluate(() => { const a = document.querySelector('.office-area').getBoundingClientRect(); return { top: Math.round(a.top), h: Math.round(a.height), vh: innerHeight } })
check('工作區吃滿剩餘高度', geo.top + geo.h >= geo.vh - 24 && geo.h > 600, JSON.stringify(geo))
await p.screenshot({ path: out + '/office-new-open.png' })
await p.click('.office-bar-btn:has-text("開啟工具")')
await p.waitForTimeout(400)
check('開啟工具選單有 13 個', await p.locator('.office-picker .office-app').count() === 13)
await p.screenshot({ path: out + '/office-new-picker.png' })
await p.click('.office-picker .office-app:has-text("Word")')
await p.waitForTimeout(1500)
check('從選單開 Word 後選單收起', await p.locator('.office-picker').count() === 0)
await p.click('.office-tab-main:has-text("Excel")')
await p.waitForTimeout(400)
const f2 = await (await p.$('iframe.office-frame--active')).contentFrame()
check('切版面後 Excel 沒被重建', await f2.evaluate(() => window.__keep) === 'kept')
await p.click('.office-bar-btn:has-text("放大")')
await p.waitForTimeout(1200)
const max = await p.evaluate(() => { const w = document.querySelector('.office-ws').getBoundingClientRect(); return { fs: !!document.fullscreenElement, w: Math.round(w.width), h: Math.round(w.height), vw: innerWidth, vh: innerHeight } })
check('放大後佔滿整個視窗', max.w >= max.vw - 2 && max.h >= max.vh - 2, JSON.stringify(max))
await p.screenshot({ path: out + '/office-new-max.png' })
const f3 = await (await p.$('iframe.office-frame--active')).contentFrame()
check('放大後 Excel 沒被重建', await f3.evaluate(() => window.__keep) === 'kept')
await p.click('.office-bar-btn:has-text("縮小")')
await p.waitForTimeout(800)
check('縮小回來', await p.evaluate(() => !document.fullscreenElement && !document.querySelector('.office-ws--max')))
const f4 = await (await p.$('iframe.office-frame--active')).contentFrame()
check('縮小後 Excel 仍沒被重建', await f4.evaluate(() => window.__keep) === 'kept')
await b.close()
console.log(fail ? `${fail} 條失敗` : '全部通過')
process.exit(fail ? 1 : 0)
